using System;

namespace CouchDeck.Input
{
    /// <summary>
    /// Button bit flags exactly as XInput reports them, plus Guide (0x0400, only via XInputGetStateEx).
    /// "Back" is the View button (two squares), "Start" is the Menu button (three lines).
    /// </summary>
    [Flags]
    public enum PadButton : ushort
    {
        None = 0,
        DPadUp = 0x0001,
        DPadDown = 0x0002,
        DPadLeft = 0x0004,
        DPadRight = 0x0008,
        Start = 0x0010,
        Back = 0x0020,
        LeftThumb = 0x0040,
        RightThumb = 0x0080,
        LeftShoulder = 0x0100,
        RightShoulder = 0x0200,
        Guide = 0x0400,
        A = 0x1000,
        B = 0x2000,
        X = 0x4000,
        Y = 0x8000
    }

    /// <summary>
    /// Snapshot of one controller at one poll. Sticks are normalised to -1..1 with the dead zone
    /// already removed, triggers to 0..1.
    /// </summary>
    public readonly struct PadState
    {
        public PadState(PadButton buttons, float leftX, float leftY, float rightX, float rightY, float leftTrigger, float rightTrigger)
        {
            Buttons = buttons;
            LeftX = leftX;
            LeftY = leftY;
            RightX = rightX;
            RightY = rightY;
            LeftTrigger = leftTrigger;
            RightTrigger = rightTrigger;
        }

        public PadButton Buttons { get; }
        public float LeftX { get; }
        public float LeftY { get; }
        public float RightX { get; }
        public float RightY { get; }
        public float LeftTrigger { get; }
        public float RightTrigger { get; }

        public bool IsDown(PadButton button) => (Buttons & button) == button;
    }

    public sealed class PadButtonEventArgs : EventArgs
    {
        public PadButtonEventArgs(int controllerIndex, PadButton button, bool isRepeat, bool isPlayStation = false)
        {
            ControllerIndex = controllerIndex;
            Button = button;
            IsRepeat = isRepeat;
            IsPlayStation = isPlayStation;
        }

        public int ControllerIndex { get; }
        public PadButton Button { get; }

        /// <summary>Pressed on a PlayStation controller (A = Cross, B = Circle, X = Square, Y = Triangle).</summary>
        public bool IsPlayStation { get; }

        /// <summary>True when generated by holding a direction (auto-repeat), not a fresh press.</summary>
        public bool IsRepeat { get; }
    }
}
